def get_child_areas(row, df: pd.DataFrame) -> list[float]:
    """
    Return list of child areas for the children listed in row['Children'],
    but only searching within the same Replicate as row['Replicate'] to avoid cross-replicate collisions.

    Parameters:
        row (pd.Series): List of dataframe rows containing Children lists.
        df (pd.DataFrame): Full dataframe generated by find_parent_children.

    Returns:
        areas (list): List of child areas (empty if areas not found).
    """

    children = row.get('Children', []) or []
    rep = row.get('Replicate', None)
    areas = []
    
    for (frame, cid) in children:
        if rep is None:
            child = df[(df['Generation Frame'] == frame) & (df['Label'] == cid)]
        else:
            child = df[(df['Replicate'] == rep) & (df['Generation Frame'] == frame) & (df['Label'] == cid)]
        if not child.empty:
            areas.append(float(child['Area'].values[0]))

    return areas


def _select_region_df(df: pd.DataFrame, region: str) -> pd.DataFrame:
    """
    Helper to pick rows which fall within a given spatial region.

    Parameters:
        df (pd.DataFrame): Input dataframe.
        region (str): Region name to select.

    Returns:
        df (pd.DataFrame): Filtered copy of df corresponding to the specified region.
    """
    
    if region == 'Global':
        return df.copy()
    
    candidates = [
        f"is_{region}",
        f"is_{region.replace(' ', '_')}",
        f"is_{region.replace(' ', '').replace('(', '').replace(')', '')}",
    ]
    
    for c in candidates:
        if c in df.columns:
            if df[c].dtype == bool or df[c].dtype == 'bool':
                return df[df[c].astype(bool)].copy()
    
    if 'Region' in df.columns:
        return df[df['Region'] == region].copy()
    
    return df.copy()




