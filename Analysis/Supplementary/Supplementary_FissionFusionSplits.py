def group_sample_data(data_parent_folder: str) -> pd.DataFrame:
    """
    Load and merge per-object morphological and mechanism event data across all samples.
    
    Parameters:
        data_parent_folder (str): Directory path containing sample folders per-replicate.

    Returns:
        pd.DataFrame: Dataframe of merged morphological and event mechanism rows.
    """

    all_data = []
    
    for sample, replicates in sample_groups.items():
        for replicate in replicates:
            folder = Path(data_parent_folder, str(replicate), "processed_data_analysis")
            morphological_csv = Path(folder, "general_morphological_features_per_object.csv")
            mechanism_csv = Path(folder, "fission_fusion_mechanisms.csv")
            if morphological_csv.exists() and mechanism_csv.exists():
                morphological_df = pd.read_csv(morphological_csv)
                fission_fusion_mechanism_df = pd.read_csv(mechanism_csv)
                
